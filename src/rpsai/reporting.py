'''The evaluation report in Markdown and every number as JSON.'''

from collections.abc import Sequence
from dataclasses import asdict
from pathlib import Path

from rpsai.export import write_json
from rpsai.gesture_pipeline import GestureResults
from rpsai.predictor_pipeline import EXPERT_LABELS, PredictorResults
from rpsai.simulation import Interval

REPORT_FILE = 'evaluation_report.md'
METRICS_FILE = 'metrics.json'
FIGURE_DIR_NAME = 'figures'
SPLIT_NAMES = {'train': 'Training', 'val': 'Validation', 'test': 'Test'}


def percent(value: float, decimals: int = 1) -> str:
    '''Format a share as a percentage.'''
    return f'{100 * value:.{decimals}f}%'


def interval(value: Interval, signed: bool = False) -> str:
    '''Format a share with its 95% interval.'''
    sign = '+' if signed else ''
    low, high = 100 * value.low, 100 * value.high
    return f'{100 * value.value:{sign}.1f}% ({low:{sign}.1f} to {high:{sign}.1f})'


def write_metrics(gestures: GestureResults, predictor: PredictorResults, path: Path) -> Path:
    '''Write every result as JSON for other tools.'''
    return write_json(
        {'gestures': asdict(gestures), 'predictor': asdict(predictor)}, path, indent=2
    )


def write_report(
    gestures: GestureResults,
    predictor: PredictorResults,
    figures: Sequence[tuple[str, Path]],
    path: Path,
) -> Path:
    '''Write the Markdown report. Figure paths are relative to the report.'''
    sections = [
        '# Evaluation report\n\n'
        'Generated by `scripts/train_and_evaluate.py`. Rerun the script rather than editing this '
        'file.',
        _gesture_section(gestures),
        _predictor_section(predictor),
        _figure_section(figures),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n\n'.join(sections) + '\n', encoding='utf-8', newline='\n')
    return path


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ['| ' + ' | '.join(header) + ' |', '| ' + ' | '.join('---' for _ in header) + ' |']
    lines += ['| ' + ' | '.join(row) + ' |' for row in rows]
    return '\n'.join(lines)


def _gesture_section(results: GestureResults) -> str:
    data = _table(
        ('Split', 'Hands', 'People'),
        [
            (SPLIT_NAMES[split], f'{results.hands[split]:,}', f'{results.people[split]:,}')
            for split in results.hands
        ],
    )
    readers = _table(
        (
            'Reader',
            'Accuracy',
            'Macro F1',
            'Threshold',
            'Moves read correctly',
            'Moves asked again',
            'Non-moves played as a move',
            'Wrong moves',
        ),
        [
            (
                reader.name,
                percent(reader.metrics.accuracy, 2),
                f'{reader.metrics.macro_f1:.4f}',
                f'{reader.metrics.threshold:.2f}' if reader.thresholded else 'none',
                percent(reader.metrics.moves_read_correctly, 2),
                percent(reader.metrics.moves_asked_again, 2),
                percent(reader.metrics.others_played_as_moves, 2),
                percent(reader.metrics.wrong_move_rate, 2),
            )
            for reader in results.readers
        ],
    )
    labels = _table(
        (
            'HaGRID label',
            'Class',
            'Hands',
            'Rock',
            'Paper',
            'Scissors',
            'Not a move',
            'Asked again',
        ),
        [
            (
                reading.label.replace('_', ' '),
                reading.gesture_class,
                f'{reading.hands:,}',
                *(percent(share) for share in reading.shares),
            )
            for reading in results.labels
        ],
    )
    stretch = _table(
        ('Reader', *(f'{value:g}' for value in results.stretches)),
        [
            (reader.name, *(percent(value) for value in reader.stretch_accuracy))
            for reader in results.readers
        ],
    )
    layers = ' and '.join(str(size) for size in results.hidden_layers)
    return '\n\n'.join(
        [
            '## Gesture reader',
            'Hands come from the HaGRID v2 annotations, split by person, so no one appears in '
            'more than one split. Each class has the same number of hands, spread evenly over '
            'its HaGRID labels.',
            data,
            f'The game uses the neural network: hidden layers of {layers} units, '
            f"{results.parameters:,} parameters. Each reader's threshold is the lowest at which "
            'it plays at most 0.25% of validation hands as a move the player did not show.',
            readers,
            '- **Moves read correctly**: rock, paper, and scissors hands read as the right move.\n'
            '- **Moves asked again**: move hands read as not a move or below the threshold. The '
            'game asks the player to show their hand again.\n'
            '- **Non-moves played as a move**: thumbs up, pointing, relaxed hands, and other '
            'non-moves that the game would play as rock, paper, or scissors.\n'
            '- **Wrong moves**: hands of any class played as a move the player did not show.',
            '### By HaGRID label',
            'Labels marked left out are between two moves, such as three fingers, and were not '
            'used in training.',
            labels,
            '### Image shape',
            "The annotations do not record each photo's aspect ratio, so the readers were "
            'trained on hands stretched vertically by random factors between 0.5 and 2. Accuracy '
            'on test hands stretched by each factor:',
            stretch,
        ]
    )


def _predictor_section(results: PredictorResults) -> str:
    settings = results.settings
    setup = _table(
        ('Setting', 'Value'),
        [
            ('Players', f'{results.players} with {results.rounds} rounds each'),
            (
                'Players left out',
                _skipped(results.skipped_players),
            ),
            ('Tuning players', str(results.tuning_players)),
            ('Test players', str(results.test_players)),
            ('Count decay', f'{settings.decay:g}'),
            ('Prior count', f'{settings.prior:g}'),
            ('Combiner learning rate', f'{settings.learning_rate:g}'),
            ('Combiner score decay', f'{settings.score_decay:g}'),
            ('Longest pattern', f'{settings.pattern_length} rounds'),
            ('Margin before playing at random', f'{settings.margin:g}'),
        ],
    )
    strategies = _table(
        ('AI strategy', 'Won', 'Drawn', 'Lost', 'Net score', 'Predicted the move', 'Log loss'),
        [
            (
                summary.name,
                interval(summary.win_rate),
                percent(summary.draw_rate),
                percent(summary.loss_rate),
                interval(summary.net_score, signed=True),
                'n/a' if summary.accuracy is None else percent(summary.accuracy),
                'n/a' if summary.log_loss is None else f'{summary.log_loss:.4f}',
            )
            for summary in results.strategies
        ],
    )
    blocks = len(results.strategies[0].win_rate_by_block)
    block_names = [f'{10 * b + 1}-{min(10 * b + 10, results.rounds)}' for b in range(blocks)]
    learning = _table(
        ('AI strategy', *block_names),
        [
            (summary.name, *(percent(value) for value in summary.win_rate_by_block))
            for summary in results.strategies
        ],
    )
    habits = results.habits
    rock, paper, scissors = habits.move_shares
    after_loss, after_draw, after_win = habits.repeat_after
    weights = results.weights_by_round[-1]
    final_weights = _table(
        ('Predictor', 'Share of the forecast in the last round'),
        [
            (EXPERT_LABELS[name], percent(weight))
            for name, weight in sorted(
                zip(results.expert_names, weights, strict=True), key=lambda item: -item[1]
            )
        ],
    )
    return '\n\n'.join(
        [
            '## Move predictor',
            'The recorded games come from Komai, Kurokawa, and Kim (2022). Players are split at '
            'random: settings are tuned on one half and every number below comes from the other '
            'half. The AI predicts each move from the history the player actually saw, so the '
            'results show how well it predicts real people, not how they would react to it.',
            setup,
            'Settings are chosen by the lowest log loss on the tuning players, then the margin by '
            f'the highest net score. The best tuning log loss was {results.best_log_loss:.4f}; '
            'random guessing scores 1.0986.',
            '### Results on the test players',
            'Intervals are 95% bootstrap intervals over players. The net score is the share of '
            'rounds won minus the share lost.',
            strategies,
            '### Win rate by round',
            learning,
            '### What the combined forecast relies on',
            final_weights,
            '### How the recorded players played',
            f'Across all {results.players} players, {percent(rock)} of moves were rock, '
            f'{percent(paper)} paper, and {percent(scissors)} scissors. Players repeated their '
            f'previous move in {percent(habits.repeat_rate)} of rounds, less than the 33.3% of '
            f'random play. They repeated {percent(after_win)} of the time after a win, '
            f'{percent(after_draw)} after a draw, and {percent(after_loss)} after a loss.',
            'The dataset does not document which number is which move. These figures assume the '
            "encoding of the authors' later work: 0 rock, 1 scissors, 2 paper. Prediction "
            'accuracy and log loss do not depend on that assumption, because every predictor '
            'treats the three moves alike. Wins do, slightly: with paper and scissors swapped, '
            f'the combined AI would win {percent(results.swapped_encoding_win_rate)} of rounds '
            f'instead of {percent(results.strategies[-1].win_rate.value)}.',
        ]
    )


def _skipped(players: Sequence[int]) -> str:
    if not players:
        return 'none'
    listed = ', '.join(f'number {player}' for player in players)
    return f'{listed}: the files of player and computer moves differ in length'


def _figure_section(figures: Sequence[tuple[str, Path]]) -> str:
    lines = ['## Figures']
    for title, figure_path in figures:
        lines += ['', f'### {title}', '', f'![{title}]({figure_path.as_posix()})']
    return '\n'.join(lines)
